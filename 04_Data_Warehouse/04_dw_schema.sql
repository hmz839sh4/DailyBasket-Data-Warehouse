-- Star schema for project_dw
SET search_path = project_dw;

-- Dimension tables

-- Calendar dimension (smart key in YYYYMMDD form)
CREATE TABLE IF NOT EXISTS dim_date (
    date_key      INT PRIMARY KEY,                -- format: YYYYMMDD
    full_date     DATE NOT NULL UNIQUE,
    day_name      VARCHAR(10),
    day_of_month  INT,
    week_of_year  INT,
    month_number  INT,
    month_name    VARCHAR(10),
    quarter       INT,
    year          INT,
    is_weekend    BOOLEAN
);

-- Customer dimension
CREATE TABLE IF NOT EXISTS dim_customer (
    customer_key      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- surrogate key
    customer_id       VARCHAR(20) NOT NULL UNIQUE,                        -- natural key
    customer_name     VARCHAR(100),
    email             VARCHAR(100),
    gender            VARCHAR(10),
    age_group         VARCHAR(15),
    customer_segment  VARCHAR(20),
    signup_date       DATE
);

-- Product dimension
CREATE TABLE IF NOT EXISTS dim_product (
    product_key   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- surrogate key
    product_id    VARCHAR(20) NOT NULL UNIQUE,                        -- natural key
    product_name  VARCHAR(100),
    brand         VARCHAR(50),
    subcategory   VARCHAR(50),
    category      VARCHAR(50),
    unit_cost     NUMERIC(10,2),
    list_price    NUMERIC(10,2),
    is_active     BOOLEAN
);

-- Region / geography dimension
CREATE TABLE IF NOT EXISTS dim_region (
    region_key   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- surrogate key
    region_id    VARCHAR(20) NOT NULL UNIQUE,                        -- natural key
    city         VARCHAR(50),
    province     VARCHAR(50),
    country      VARCHAR(50),
    region_zone  VARCHAR(20)
);

-- Sales channel dimension
CREATE TABLE IF NOT EXISTS dim_channel (
    channel_key   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- surrogate key
    channel_id    VARCHAR(20) NOT NULL UNIQUE,                        -- natural key
    channel_name  VARCHAR(30),
    channel_type  VARCHAR(20)
);

-- Promotion dimension
CREATE TABLE IF NOT EXISTS dim_promotion (
    promotion_key     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- surrogate key; 0 = No Promotion
    promotion_id      VARCHAR(20) NOT NULL UNIQUE,                        -- natural key
    promotion_name    VARCHAR(60),
    promotion_type    VARCHAR(30),
    discount_percent  NUMERIC(5,2),
    start_date        DATE,
    end_date          DATE
);

-- Fact tables

-- Sales fact
-- Grain: one row per product on one order (i.e. one order line)
CREATE TABLE IF NOT EXISTS fact_sales (
    sales_key          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    date_key           INT NOT NULL REFERENCES dim_date (date_key),
    customer_key       INT NOT NULL REFERENCES dim_customer (customer_key),
    product_key        INT NOT NULL REFERENCES dim_product (product_key),
    region_key         INT NOT NULL REFERENCES dim_region (region_key),
    channel_key        INT NOT NULL REFERENCES dim_channel (channel_key),
    promotion_key      INT NOT NULL REFERENCES dim_promotion (promotion_key),
    order_id           VARCHAR(20) NOT NULL,          -- degenerate dimension
    order_line_number  INT NOT NULL,                  -- degenerate dimension
    quantity           INT NOT NULL CHECK (quantity > 0),
    unit_price         NUMERIC(10,2) NOT NULL,
    discount_amount    NUMERIC(12,2) NOT NULL,
    gross_amount       NUMERIC(12,2) NOT NULL,
    net_revenue        NUMERIC(12,2) NOT NULL,
    cost_amount        NUMERIC(12,2) NOT NULL,
    profit_amount      NUMERIC(12,2) NOT NULL,
    CONSTRAINT uq_fact_sales_line UNIQUE (order_id, order_line_number)   -- guards against double loading
);

-- Inventory snapshot fact
-- Grain: one row per product per region, taken at end of day
CREATE TABLE IF NOT EXISTS fact_inventory_snapshot (
    inventory_snapshot_key  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    date_key           INT NOT NULL REFERENCES dim_date (date_key),
    product_key        INT NOT NULL REFERENCES dim_product (product_key),
    region_key         INT NOT NULL REFERENCES dim_region (region_key),
    quantity_on_hand   INT NOT NULL CHECK (quantity_on_hand >= 0),
    quantity_received  INT NOT NULL,
    quantity_sold      INT NOT NULL,
    reorder_level      INT NOT NULL,
    stock_value        NUMERIC(12,2) NOT NULL,
    CONSTRAINT uq_fact_inventory UNIQUE (date_key, product_key, region_key)
);

-- Promotion event fact (factless: it holds keys only, no measures)
-- Grain: one row per product per promotion per active day
CREATE TABLE IF NOT EXISTS fact_promotion_event (
    date_key       INT NOT NULL REFERENCES dim_date (date_key),
    product_key    INT NOT NULL REFERENCES dim_product (product_key),
    promotion_key  INT NOT NULL REFERENCES dim_promotion (promotion_key),
    PRIMARY KEY (date_key, product_key, promotion_key)
);

-- Indexes on the foreign keys of fact_sales
CREATE INDEX IF NOT EXISTS ix_fact_sales_date     ON fact_sales (date_key);
CREATE INDEX IF NOT EXISTS ix_fact_sales_customer ON fact_sales (customer_key);
CREATE INDEX IF NOT EXISTS ix_fact_sales_product  ON fact_sales (product_key);
CREATE INDEX IF NOT EXISTS ix_fact_sales_region   ON fact_sales (region_key);


